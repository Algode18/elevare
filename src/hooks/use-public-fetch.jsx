import { useState } from "react";

// Like useFetch, but for public pages (job listing, job details, companies).
// Does not depend on a Clerk session, so it works for signed-out guests too.
const usePublicFetch = (cb, options = {}) => {
  const [data, setData] = useState(undefined);
  const [loading, setLoading] = useState(null);
  const [error, setError] = useState(null);

  const fn = async (...args) => {
    setLoading(true);
    setError(null);
    try {
      const response = await cb(undefined, options, ...args);
      setData(response);
      setError(null);
    } catch (error) {
      setError(error);
    } finally {
      setLoading(false);
    }
  };

  return { data, loading, error, fn };
};

export default usePublicFetch;
